class _CountingHandler(logging.Handler):
    """Captures-and-counts the components' own verdict records."""

    def __init__(self, counter: Counter[str]) -> None:
        super().__init__()
        self._counter = counter

    def emit(self, record: logging.LogRecord) -> None:
        try:
            message = record.getMessage()
        except Exception:
            return
        for prefix in _OBSERVED_LOG_PREFIXES:
            if message.startswith(prefix):
                self._counter[prefix] += 1
                return


class _LogCountObserver:
    """Counts the production components' own verdict log records.

    Purely observational: it never mutates production objects and never
    suppresses logging (handlers are additive and removed on close).
    The canonical counters come from the production objects themselves;
    these log verdicts are the secondary trail for paths (risk skips,
    route blocks) that do not expose per-cycle counters."""

    _LOGGER_NAMES = (
        "core.setup.decision_engine",
        "core.risk.risk_engine",
        "core.live.broker_engine",
        "core.runtime.realtime_engine",
    )

    def __init__(self) -> None:
        self.counts: Counter[str] = Counter()
        self._handlers: list[logging.Handler] = []
        self._previous_levels: dict[str, int | None] = {}
        for name in self._LOGGER_NAMES:
            logger = logging.getLogger(name)
            # Verdict records are INFO-level; the default unconfigured root
            # level (WARNING) would drop them before any handler runs.
            # Additive and restored on detach — never a suppression.
            self._previous_levels[name] = (
                logger.level if logger.level else None
            )
            logger.setLevel(logging.INFO)
            handler = _CountingHandler(self.counts)
            logger.addHandler(handler)
            self._handlers.append(handler)

    def detach(self) -> None:
        for name in self._LOGGER_NAMES:
            logger = logging.getLogger(name)
            for handler in self._handlers:
                try:
                    logger.removeHandler(handler)
                except Exception:
                    pass
            previous = self._previous_levels.get(name, None)
            if previous is None:
                logger.setLevel(logging.NOTSET)
            else:
                logger.setLevel(previous)

    def snapshot(self) -> dict[str, int]:
        return dict(sorted(self.counts.items()))


