class _ReplayInstrument:
    """Explicit-cut instrument duck for the offline replay assembly."""

    def __init__(self, symbol: str) -> None:
        self.symbol = symbol
        self.exchange = "DELTA"
        self.instrument_id = symbol


class _ExplicitUniverseDuck:
    """The documented explicit-cut universe manager duck (offline).

    Returns a universe containing exactly the configured symbols -- the
    eligible cut is explicit configuration, never a hardcoded engine
    list and never a discovery call."""

    def __init__(self, symbols: Iterable[str]) -> None:
        self._symbols = list(symbols)
        self.discovery_attempts = 0

    def refresh_discovery(self, client=None, normalizer=None):
        self.discovery_attempts += 1
        return {"explicit": True, "instruments": len(self._symbols)}

    def build_universe(self, timeframe="1m"):
        return MarketUniverse(
            policy=UniversePolicy(),
            instruments=[_ReplayInstrument(s) for s in self._symbols],
            timeframe=timeframe or "1m",
            captured_at=0,
        )


class VerifiedTransportReplay:
    """Deterministic replay harness over the verified-transport seam.

    Builds the REAL production assembly once (verified transport +
    MultiSymbolSubscriptionManager/SubscriptionWorker + RealTimeEngine +
    frozen InstitutionalPipeline world), then feeds frame records in
    receipt order with explicit fault injection.  ``speed=0`` is fully
    deterministic (no wall-clock waits); ``speed>0`` adds optional
    operator pacing in a run script (never used by the tests).
    """

    def __init__(
        self,
        symbols: Iterable[str],
        *,
        resolution: str = "1m",
        clock: ReplayClock | None = None,
        seed: int | None = None,
        max_reconnect_attempts: int | None = 6,
        base_delay: float = 0.5,
        refresh_interval_seconds: float = 3_600.0,
        max_stale_seconds: float = 30.0,
    ) -> None:
        self.symbols = [str(s) for s in symbols]
        if not self.symbols:
            raise ValueError("replay requires at least one symbol")
        self.resolution = resolution
        self.clock = clock if clock is not None else ReplayClock()
        self.seed = seed
        self._memory_peak_mb = 0.0
        self.transport = VerifiedPublicCandleTransport(resolution=resolution)
        self.universe_manager = _ExplicitUniverseDuck(self.symbols)
        self.manager = MultiSymbolSubscriptionManager(
            transport_factory=lambda: self.transport,
            clock=self.clock,
            policy=ReconnectPolicy(
                base_delay=base_delay, max_attempts=max_reconnect_attempts,
            ),
            candles_callback=lambda candle: self.engine._on_closed_candle(
                candle,
            ),
            max_stale_seconds=max_stale_seconds,
        )
        self.engine = RealTimeEngine(
            universe_manager=self.universe_manager,
            refresh_scheduler=RefreshScheduler(
                manager=self.universe_manager,
                interval_seconds=refresh_interval_seconds,
                clock=self.clock,
            ),
            subscription_manager=self.manager,
            clock=self.clock,
            timeframe=resolution,
        )
        self._log_observer = _LogCountObserver()
        self._started = False

    # ------------------------------------------------------------------
    # lifecycle
    # ------------------------------------------------------------------

    def start(self) -> None:
        """Build the universe + pipelines + subscriptions (real path)."""
        self.engine.start()
        self._started = True

    def stop(self) -> None:
        """Stop the engine (known-safe state: subscriptions torn down)."""
        self.engine.stop()
        self._started = False

    def close(self) -> None:
        self._log_observer.detach()

    def poll(self) -> None:
        """One engine poll step (refresh-if-due + worker pump)."""
        self.engine.poll()

    # ------------------------------------------------------------------
    # ingress
    # ------------------------------------------------------------------

    def ingest(self, frame: Any, *, receipt_timestamp: Any) -> dict[str, Any]:
        """Feed one frame through the REAL verified transport seam."""
        return self.transport.ingest(
            frame, receipt_timestamp=receipt_timestamp,
        )

    def notify_down(self, symbol: str | None = None) -> None:
        self.transport.notify_down(symbol)

    def resubscribe_after_outage(self, symbol: str | None = None) -> None:
        """Advance the clock past the reconnect deadline and pump the
        engine once, so a torn-down subscription's scheduled retry runs
        (the documented RECONNECTING -> retry -> LIVE path)."""
        self.clock.advance(2.0)
        self.poll()

    def repair_gap_history(
        self, symbol: str, resolution: str, candles, *,
        receipt_timestamp: int,
    ) -> dict:
        return self.transport.repair_gap_history(
            symbol, resolution, candles,
            receipt_timestamp=receipt_timestamp,
        )

    def continuity_status(
        self, symbol: str, resolution: str | None = None,
    ) -> dict[str, Any]:
        return self.transport.continuity_status(symbol, resolution)

    def runtime(self, symbol: str) -> Any | None:
        """The PaperRuntime owning ``symbol`` (test/operator inspection)."""
        for runtime in self.engine.runtimes.values():
            if getattr(runtime, "symbol", "") == symbol:
                return runtime
        return None

    # ------------------------------------------------------------------
    # outcome capture (production observability only)
    # ------------------------------------------------------------------

    def _pipeline_processed(self) -> dict[str, int]:
        out: dict[str, int] = {}
        for runtime in self.engine.runtimes.values():
            symbol = getattr(runtime, "symbol", "")
            stats = getattr(
                getattr(getattr(runtime, "pipeline", None), "world", None),
                "statistics", None,
            )
            out[symbol] = int(getattr(stats, "processed", 0) or 0)
        return out

    def _decision_stage(self, runtime) -> Any | None:
        world = getattr(getattr(runtime, "pipeline", None), "world", None)
        for stage in getattr(world, "engines", []) or []:
            if type(stage).__name__ == "DecisionEngine":
                return stage
        return None

    def capture_cycle_outcomes(self) -> dict[str, dict[str, Any]]:
        """Per-symbol snapshot of the LAST completed pipeline cycle.

        Valid immediately after an ingest that delivered a closed candle
        (the cycle runs synchronously inside the transport callback):
        setups, decision verdicts, the risk-approved order and the
        routed-order delta are read from the production objects.
        """
        out: dict[str, dict[str, Any]] = {}
        for _key, runtime in self.engine.runtimes.items():
            symbol = getattr(runtime, "symbol", "") or str(_key)
            pipeline = getattr(runtime, "pipeline", None)
            context = getattr(pipeline, "context", None)
            if context is None:
                continue
            decision_stage = self._decision_stage(runtime)
            decision = getattr(context, "decision", None)
            accepted = list(decision.all()) if (
                decision is not None and hasattr(decision, "all")
            ) else []
            rejected_reasons: list[str] = []
            for reject in getattr(decision_stage, "rejected", None) or []:
                rejected_reasons.extend(
                    getattr(reject, "reasons", None) or [],
                )
            broker = getattr(runtime, "engine", None)
            out[symbol] = {
                "setups": len(getattr(context, "trade_setups", None) or []),
                "decision_accepted": len(accepted),
                "decision_accepted_rr": [
                    round(
                        float(getattr(candidate, "risk_reward", 0.0) or 0.0),
                        6,
                    )
                    for candidate in accepted
                ],
                "decision_rejected": tuple(rejected_reasons),
                "risk_order": bool(getattr(context, "order", None)),
                "orders_placed": len(getattr(broker, "placed", None) or []),
                "trades_closed": len(
                    (getattr(broker, "registry", None).all() or [])
                ) if broker is not None and getattr(broker, "registry", None) else 0,
            }
        return out

    def snapshot(self) -> dict[str, Any]:
        """Full observability snapshot of the production assembly."""
        transport_stats = self.transport.stats()
        workers: dict[str, dict[str, Any]] = {}
        for symbol, state in self.engine.subscriptions.statuses().items():
            workers[symbol] = {
                "status": str(getattr(state, "status", "")),
                "received": int(getattr(state, "received", 0) or 0),
                "delivered": int(getattr(state, "delivered", 0) or 0),
                "duplicates": int(getattr(state, "duplicates", 0) or 0),
                "out_of_order": int(getattr(state, "out_of_order", 0) or 0),
                "forming_skipped": int(
                    getattr(state, "forming_skipped", 0) or 0,
                ),
            }
        pipelines: dict[str, Any] = {}
        decision_accepted_total = 0
        paper_orders = 0
        paper_trades_closed = 0
        equity_start = 0.0
        equity_end = 0.0
        processed = 0
        for symbol, runtime in self.engine.runtimes.items():
            pipeline = getattr(runtime, "pipeline", None)
            stats = getattr(
                getattr(pipeline, "world", None), "statistics", None,
            )
            processed += int(getattr(stats, "processed", 0) or 0)
            decision_stage = self._decision_stage(runtime)
            registry = getattr(decision_stage, "accepted", None)
            if registry is not None and hasattr(registry, "all"):
                decision_accepted_total += len(registry.all() or ())
            broker = getattr(runtime, "engine", None)
            paper_orders += len(getattr(broker, "placed", None) or [])
            ledger = getattr(broker, "registry", None)
            if ledger is not None:
                paper_trades_closed += len(ledger.all() or ())
            account = getattr(broker, "account", None)
            state = getattr(account, "state", account)
            equity_start += float(
                getattr(state, "starting_balance", 0.0) or 0.0,
            )
            equity_end += float(getattr(state, "equity", 0.0) or 0.0)
        return {
            "transport": {
                "frames_ingested": int(transport_stats["frames_ingested"]),
                "forming_delivered": int(
                    transport_stats["forming_delivered"],
                ),
                "closed_delivered": int(
                    transport_stats["closed_delivered"],
                ),
                "unrouted": int(transport_stats["unrouted"]),
                "runtime_rejections": dict(
                    transport_stats["runtime_rejections"],
                ),
                "stream": dict(transport_stats["stream"]),
            },
            "workers": workers,
            "engine": {
                "routed": int(self.engine.routed),
                "unrouted": int(self.engine.unrouted),
                "route_errors": int(self.engine.route_errors),
                "reconcile_errors": int(self.engine.reconcile_errors),
                "registry_count": int(self.engine.registry.count),
                "last_route_error": str(self.engine.last_route_error or ""),
            },
            "pipeline": {
                "candles_processed": processed,
                "registry_symbols": sorted(
                    getattr(rt, "symbol", "") or ""
                    for rt in self.engine.runtimes.values()
                ),
            },
            "risk": {
                # Registry holds only the CURRENT cycle's accepts (it is
                # cleared at each analyze); the cumulative total travels
                # in the ReplayReport risk section, accumulated per cycle
                # by run().
                "decision_accepted_last_cycle": decision_accepted_total,
                "orders_created_placed": paper_orders,
            },
            "paper": {
                "orders_placed": paper_orders,
                "trades_closed": paper_trades_closed,
                "equity_start": equity_start,
                "equity_end": equity_end,
            },
            "log_verdicts": self._log_observer.snapshot(),
        }

    # ------------------------------------------------------------------
    # the replay loop
    # ------------------------------------------------------------------

    def run(
        self,
        records: Iterable[ReplayFrame],
        *,
        speed: float = 0.0,
        faults: Iterable[Any] = (),
        max_frames: int | None = None,
        stop_check: Callable[[], bool] | None = None,
        measure: bool = False,
    ) -> "ReplayReport":
        """Replay frame records in order with optional fault injection.

        ``speed=0`` (default) is fully deterministic: no wall-clock
        waits, no sleeps.  ``speed>0`` paces frames by their recorded
        receipt deltas divided by ``speed`` (operator scripts only;
        never used by the tests).

        Faults are explicit plan objects; every injected synthetic frame
        is labelled and counted under ``synthetic_frames_injected``.
        """
        records = list(records)
        fault_list = list(faults)
        for fault in fault_list:
            if type(fault) not in FAULT_KINDS:
                raise TypeError(
                    "unsupported fault plan object: %r" % (type(fault),)
                )
        wall = time.monotonic()
        any_synthetic = any(record.synthetic for record in records)
        tracing = measure and not tracemalloc.is_tracing()
        if tracing:
            tracemalloc.start()
        report = ReplayReport(
            source_path="",
            evidence_class=(
                "SYNTHETIC_FIXTURE" if any_synthetic else "CAPTURED"
            ),
            frames_input=len(records),
            speed=speed,
            deterministic=(speed == 0.0),
            seed=self.seed,
            faults_applied=tuple(
                "%s@%d" % (type(f).__name__, getattr(f, "after_ordinal", -1))
                for f in fault_list
            ),
        )
        previous_receipt = None
        pending_resubscribes: list[tuple[DisconnectFault, int]] = []
        gap_skip_remaining = 0
        injected = 0
        skipped = 0
        disconnects: Counter[str] = Counter()
        latencies: list[float] = []
        by_ordinal = {record.ordinal: record for record in records}
        candle_ordinals = [
            record.ordinal for record in records
            if isinstance(record.frame, dict)
            and str(record.frame.get("type", "")).startswith("candlestick_")
        ]
        ordinal_index = {
            ordinal: position
            for position, ordinal in enumerate(candle_ordinals)
        }
        duplicate_observations: list[dict[str, Any]] = []
        risk_accumulator: dict[str, Any] = {
            "setups_seen_total": 0,
            "decision_accepted_total": 0,
            "decision_accepted_rr": [],
            "decision_rejected_total": 0,
            "orders_created_placed": 0,
        }

        for record in records:
            if max_frames is not None and (
                report.frames_ingested >= max_frames
            ):
                break
            if stop_check is not None and stop_check():
                break
            ordinal = record.ordinal

            # ---- scheduled reconnect retries (resubscribe seam) ----
            for fault, countdown in list(pending_resubscribes):
                if countdown <= 0:
                    pending_resubscribes.remove((fault, countdown))
                    self.resubscribe_after_outage(
                        fault.symbol if fault.symbol else None,
                    )
                    disconnects["resubscribed"] += 1
            pending_resubscribes = [
                (fault, countdown - 1)
                for fault, countdown in pending_resubscribes
            ]

            # ---- disconnect faults (drop the subscription) ----
            for fault in fault_list:
                if isinstance(fault, DisconnectFault) and (
                    fault.after_ordinal == ordinal
                ):
                    self.notify_down(fault.symbol)
                    disconnects["notify_down"] += 1
                    if fault.resubscribe_after > 0:
                        pending_resubscribes.append(
                            (fault, fault.resubscribe_after),
                        )
                    else:
                        self.resubscribe_after_outage(
                            fault.symbol if fault.symbol else None,
                        )
                        disconnects["resubscribed"] += 1

            # ---- gap fault: skip candle frames (creates a real gap) ----
            if gap_skip_remaining > 0:
                if isinstance(record.frame, dict) and str(
                    record.frame.get("type", ""),
                ).startswith("candlestick_"):
                    gap_skip_remaining -= 1
                    skipped += 1
                    continue

            # ---- pacing (speed > 0 only) ----
            if speed > 0.0 and previous_receipt is not None and (
                record.receipt_ns is not None
            ):
                delta_ns = record.receipt_ns - previous_receipt
                if delta_ns > 0:
                    time.sleep(min(delta_ns / 1e9 / speed, 1.0))
            previous_receipt = record.receipt_ns

            # ---- real ingest through the verified seam ----
            processed_before = self._pipeline_processed()
            placed_before = {
                symbol: len(
                    getattr(getattr(rt, "engine", None), "placed", None) or [],
                )
                for symbol, rt in self.engine.runtimes.items()
            }
            if measure:
                t0 = time.perf_counter()
            result = self.ingest(
                record.frame, receipt_timestamp=record.receipt_ns,
            )
            if measure:
                latencies.append((time.perf_counter() - t0) * 1000.0)
            report.frames_ingested += 1
            if isinstance(record.frame, dict) and str(
                record.frame.get("type", ""),
            ).startswith("candlestick_"):
                for fault in fault_list:
                    if isinstance(fault, GapFault) and (
                        fault.after_ordinal == ordinal
                    ):
                        gap_skip_remaining = fault.missing_candles
            processed_after = self._pipeline_processed()
            delivered_symbols = [
                symbol
                for symbol, count in processed_after.items()
                if count > processed_before.get(symbol, 0)
            ]
            for symbol in delivered_symbols:
                outcomes = self.capture_cycle_outcomes().get(symbol, {})
                runtime_now = self.runtime(symbol)
                placed_now = len(
                    getattr(getattr(runtime_now, "engine", None),
                            "placed", None) or [],
                )
                outcomes.setdefault("setups", 0)
                outcomes.setdefault("decision_accepted", 0)
                outcomes.setdefault("decision_accepted_rr", [])
                outcomes.setdefault("decision_rejected", ())
                risk_accumulator["setups_seen_total"] += int(
                    outcomes["setups"],
                )
                risk_accumulator["decision_accepted_total"] += int(
                    outcomes["decision_accepted"],
                )
                risk_accumulator["decision_accepted_rr"].extend(
                    outcomes["decision_accepted_rr"],
                )
                risk_accumulator["decision_rejected_total"] += len(
                    outcomes["decision_rejected"],
                )
                duplicate_observations.append({
                    "ordinal": ordinal,
                    "synthetic": record.synthetic,
                    "symbol": symbol,
                    "ingest_status": str(result.get("ingest_status", "")),
                    "setups": outcomes.get("setups", 0),
                    "decision_accepted": outcomes.get("decision_accepted", 0),
                    "decision_accepted_rr": list(
                        outcomes.get("decision_accepted_rr", ()),
                    ),
                    "decision_rejected": list(
                        outcomes.get("decision_rejected", ()),
                    ),
                    "risk_order": outcomes.get("risk_order", False),
                    "orders_placed_delta": placed_now - placed_before.get(
                        symbol, 0,
                    ),
                })

            # ---- post-ingest faults ----
            for fault in fault_list:
                if isinstance(fault, DuplicateFault) and (
                    fault.after_ordinal == ordinal
                ):
                    self.ingest(
                        record.frame,
                        receipt_timestamp=(
                            (record.receipt_ns or 0) + 1_000_000
                        ),
                    )
                    injected += 1
                elif isinstance(fault, OutOfOrderFault) and (
                    fault.after_ordinal == ordinal
                ):
                    position = ordinal_index.get(ordinal, 0)
                    back = candle_ordinals[
                        max(0, position - fault.back_steps)
                    ]
                    older = by_ordinal.get(back)
                    if older is not None:
                        self.ingest(
                            older.frame,
                            receipt_timestamp=(
                                (record.receipt_ns or 0) + 2_000_000
                            ),
                        )
                        injected += 1
                elif isinstance(fault, MalformedFault) and (
                    fault.after_ordinal == ordinal
                ):
                    self.ingest(
                        self._malformed_frame(record.frame, fault.mode),
                        receipt_timestamp=(
                            (record.receipt_ns or 0) + 3_000_000
                        ),
                    )
                    injected += 1

        # ---- final production observability ----
        snapshot = self.snapshot()
        report.stream = snapshot["transport"]["stream"]
        report.transport = {
            key: value
            for key, value in snapshot["transport"].items()
            if key != "stream"
        }
        report.workers = snapshot["workers"]
        report.engine = snapshot["engine"]
        report.pipeline = snapshot["pipeline"]
        # Cumulative, cycle-accumulated risk trail (authoritative for the
        # run); the snapshot's per-cycle registry state travels separately.
        risk_accumulator["orders_created_placed"] = int(
            snapshot["paper"]["orders_placed"],
        )
        risk_accumulator["decision_accepted_rr"] = sorted(
            risk_accumulator["decision_accepted_rr"],
        )
        report.risk = risk_accumulator
        report.paper = snapshot["paper"]
        report.log_verdicts = snapshot["log_verdicts"]
        report.disconnects = dict(sorted(disconnects.items()))
        report.synthetic_frames_injected = injected
        report.skipped_for_gap = skipped
        report.unrouted_during_outage = int(
            self.transport.stats()["unrouted"],
        )
        report.gaps = self.gap_report()
        report.observations = tuple(duplicate_observations)
        if measure and latencies:
            ordered = sorted(latencies)
            report.latency_ms = {
                "p50": round(statistics.median(latencies), 3),
                "p95": round(
                    ordered[min(len(ordered) - 1, int(0.95 * len(ordered)))],
                    3,
                ),
                "max": round(ordered[-1], 3),
                "mean": round(statistics.fmean(latencies), 3),
            }
        report.runtime_seconds = round(time.monotonic() - wall, 3)
        if tracing:
            _current, peak = tracemalloc.get_traced_memory()
            tracemalloc.stop()
            report.memory_peak_mb = round(peak / (1024.0 * 1024.0), 3)
            self._memory_peak_mb = report.memory_peak_mb
        return report

    # ------------------------------------------------------------------
    # helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _malformed_frame(frame: Any, mode: str) -> Any:
        """Build a SYNTHETIC malformed frame from a real captured shape.

        The modification is a labelled test artifact, never presented as
        captured evidence.
        """
        if mode == "not_a_mapping":
            return ["candlestick_1m", "synthetic-malformed"]
        if not isinstance(frame, dict):
            return frame
        broken = dict(frame)
        if mode == "drop_volume":
            broken.pop("v", None)
        elif mode == "drop_symbol":
            broken.pop("sy", None)
        elif mode == "impossible_ohlc":
            broken["h"] = 1.0
            broken["l"] = 2.0
        elif mode == "empty_symbol":
            broken["sy"] = ""
        else:
            raise ValueError("unknown malformed mode: %r" % (mode,))
        return broken

    def gap_report(self) -> dict[str, Any]:
        """Continuity/gap state of every tracked symbol (production view)."""
        out: dict[str, Any] = {"statuses": {}}
        tracker = self.transport._stream.continuity
        keys = set(getattr(tracker, "_latest", {})) | set(
            getattr(tracker, "_gaps", {}),
        )
        for key in sorted(keys):
            venue, instrument, resolution = key
            out["statuses"]["%s:%s:%s" % key] = (
                self.transport.continuity_status(instrument, resolution)
            )
        return out


@dataclass
class ReplayReport:
    """Structured outcome of one replay run.

    ``counts`` sections are deterministic for identical inputs;
    ``non_deterministic`` sections (latency/runtime/memory) are
    observations, never acceptance criteria."""

    schema: str = REPLAY_SCHEMA
    source_path: str = ""
    evidence_class: str = "CAPTURED"
    endpoint: str | None = None
    symbol: str | None = None
    frames_input: int = 0
    speed: float = 0.0
    deterministic: bool = True
    seed: int | None = None
    faults_applied: tuple[str, ...] = ()
    frames_ingested: int = 0
    synthetic_frames_injected: int = 0
    skipped_for_gap: int = 0
    unrouted_during_outage: int = 0
    stream: dict[str, int] = field(default_factory=dict)
    transport: dict[str, Any] = field(default_factory=dict)
    workers: dict[str, dict[str, Any]] = field(default_factory=dict)
    engine: dict[str, Any] = field(default_factory=dict)
    pipeline: dict[str, Any] = field(default_factory=dict)
    risk: dict[str, Any] = field(default_factory=dict)
    paper: dict[str, Any] = field(default_factory=dict)
    gaps: dict[str, Any] = field(default_factory=dict)
    disconnects: dict[str, Any] = field(default_factory=dict)
    log_verdicts: dict[str, int] = field(default_factory=dict)
    latency_ms: dict[str, float] = field(default_factory=dict)
    runtime_seconds: float = 0.0
    memory_peak_mb: float = 0.0
    observations: tuple[dict[str, Any], ...] = ()

    def to_dict(self, *, include_observations: bool = False) -> dict[str, Any]:
        payload: dict[str, Any] = {
            "schema": self.schema,
            "source_path": self.source_path,
            "evidence_class": self.evidence_class,
            "endpoint": self.endpoint,
            "symbol": self.symbol,
            "speed": self.speed,
            "deterministic": self.deterministic,
            "seed": self.seed,
            "faults_applied": list(self.faults_applied),
            "counts": {
                "frames_input": self.frames_input,
                "frames_ingested": self.frames_ingested,
                "synthetic_frames_injected": self.synthetic_frames_injected,
                "skipped_for_gap": self.skipped_for_gap,
                "unrouted_during_outage": self.unrouted_during_outage,
                "stream": self.stream,
                "transport": self.transport,
                "workers": self.workers,
                "engine": self.engine,
                "pipeline": self.pipeline,
                "risk": self.risk,
                "paper": self.paper,
                "gaps": self.gaps,
                "disconnects": self.disconnects,
                "log_verdicts": self.log_verdicts,
            },
            "non_deterministic": {
                "latency_ms": self.latency_ms,
                "runtime_seconds": self.runtime_seconds,
                "memory_peak_mb": self.memory_peak_mb,
            },
        }
        if include_observations:
            payload["observations"] = [
                {
                    "ordinal": obs.get("ordinal"),
                    "synthetic": obs.get("synthetic"),
                    "symbol": obs.get("symbol"),
                    "ingest_status": obs.get("ingest_status"),
                    "setups": obs.get("setups"),
                    "decision_accepted": obs.get("decision_accepted"),
                    "decision_accepted_rr": obs.get("decision_accepted_rr"),
                    "decision_rejected": obs.get("decision_rejected"),
                    "risk_order": obs.get("risk_order"),
                    "orders_placed_delta": obs.get("orders_placed_delta"),
                }
                for obs in self.observations
            ]
        return payload

    def to_json(self, *, include_observations: bool = False) -> str:
        return json.dumps(
            self.to_dict(include_observations=include_observations),
            indent=2, sort_keys=True, default=str,
        ) + "\n"


# ==================================================================
# Reconciliation (paper ledger vs account state; production math only)
# ==================================================================


def reconcile_paper_ledger(harness: VerifiedTransportReplay) -> dict[str, Any]:
    """Cross-check each runtime's paper ledger against its account state.

    Equity must equal starting balance plus realized PnL of completed
    ledger trades (the canonical accounting identity the paper stack is
    certified against).  Reports the reconciliation verdict per symbol;
    never mutates state and never invents a trade.
    """
    out: dict[str, Any] = {"symbols": {}, "consistent": True}
    for symbol, runtime in harness.engine.runtimes.items():
        broker = getattr(runtime, "engine", None)
        account = getattr(broker, "account", None)
        ledger = getattr(broker, "registry", None)
        if account is None or ledger is None:
            continue
        state = getattr(account, "state", account)
        completed = ledger.all()
        realized = sum(
            float(getattr(t, "pnl", 0.0) or 0.0) for t in completed
        )
        starting = float(getattr(state, "starting_balance", 0.0) or 0.0)
        equity = float(getattr(state, "equity", 0.0) or 0.0)
        open_positions = (
            1 if getattr(broker, "_live_trade", None) is not None else 0
        )
        verdict = {
            "starting_balance": starting,
            "equity": equity,
            "completed_trades": len(completed),
            "realized_pnl": round(realized, 8),
            "open_positions": open_positions,
            "equity_minus_start_minus_realized": round(
                equity - starting - realized, 8,
            ),
            "reconciled": math.isclose(
                equity, starting + realized, abs_tol=1e-6,
            ),
        }
        out["symbols"][symbol] = verdict
        out["consistent"] = out["consistent"] and verdict["reconciled"]
    return out
