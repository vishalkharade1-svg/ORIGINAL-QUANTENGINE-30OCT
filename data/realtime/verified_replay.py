@dataclass(frozen=True, slots=True)
class DuplicateFault:
    """Re-ingest one already-delivered captured candle frame verbatim."""

    after_ordinal: int


@dataclass(frozen=True, slots=True)
class OutOfOrderFault:
    """Re-ingest an older captured candle frame after ``after_ordinal``."""

    after_ordinal: int
    back_steps: int = 2


@dataclass(frozen=True, slots=True)
class MalformedFault:
    """Inject one synthetic malformed frame after ``after_ordinal``.

    Modes: ``not_a_mapping``, ``drop_volume``, ``drop_symbol``,
    ``impossible_ohlc``, ``empty_symbol``.
    """

    after_ordinal: int
    mode: str


@dataclass(frozen=True, slots=True)
class GapFault:
    """Skip the next ``missing_candles`` candle frames (creates a real
    continuity gap in the shared stream state)."""

    after_ordinal: int
    missing_candles: int = 2


@dataclass(frozen=True, slots=True)
class DisconnectFault:
    """Signal a stream drop at ``after_ordinal`` (notify_down fan-out +
    registration teardown).  When ``resubscribe_after`` > 0, that many
    further records are ingested while torn down (counted ``unrouted``,
    fail-closed) before the clock-advanced reconnect retry restores
    LIVE delivery; when 0 the retry runs immediately."""

    after_ordinal: int
    symbol: str | None = None
    resubscribe_after: int = 0


FAULT_KINDS = (
    DuplicateFault, OutOfOrderFault, MalformedFault,
    GapFault, DisconnectFault,
)


