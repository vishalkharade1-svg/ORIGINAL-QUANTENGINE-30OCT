@dataclass(frozen=True, slots=True)
class ReplayFrame:
    """One ordered frame record to replay.

    ``ordinal`` preserves the capture's receipt ordering.  ``receipt_ns``
    is the recorded (or deterministic synthetic) receipt time in
    nanoseconds; at ``speed=0`` it is metadata only.  ``synthetic``
    marks frames that were generated by this harness, never by an
    exchange.
    """

    ordinal: int
    frame: Any
    receipt_ns: int | None
    synthetic: bool = False


@dataclass(frozen=True, slots=True)
class CaptureBundle:
    """Parsed capture bundle with its evidence class attached."""

    source_path: str
    schema: str
    endpoint: str | None
    symbol: str | None
    evidence_class: str  # "CAPTURED" or "SYNTHETIC_FIXTURE"
    records: tuple[ReplayFrame, ...]

    @property
    def is_captured(self) -> bool:
        return self.evidence_class == "CAPTURED"


def load_capture(path: str | Path) -> CaptureBundle:
    """Parse a recorded ``quantengine.delta-public-capture.v1`` bundle.

    Frames are returned strictly in stored ``receipt_ordinal`` order.
    ``receipt_unix_ns`` is carried verbatim when recorded; otherwise a
    ``None`` receipt is preserved (the stream still requires a receipt
    argument, which the caller supplies).
    """
    bundle = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(bundle, dict):
        raise ValueError("capture file must contain a JSON object")
    if bundle.get("schema") != CAPTURE_SCHEMA:
        raise ValueError(
            "unsupported capture schema: %r" % (bundle.get("schema"),)
        )
    records = bundle.get("frames")
    if not isinstance(records, list):
        raise ValueError("capture bundle has no frames list")
    parsed: list[ReplayFrame] = []
    for index, record in enumerate(records, start=1):
        if isinstance(record, dict) and isinstance(record.get("frame"), dict):
            frame: Any = record["frame"]
        else:
            # preserved (rare malformed record): replayed as-is so the
            # stream's fail-closed rejection of it stays observable
            frame = record
        receipt_ns = record.get("receipt_unix_ns") if isinstance(
            record, dict,
        ) else None
        if not isinstance(receipt_ns, int):
            receipt_ns = None
        ordinal = record.get("receipt_ordinal") if isinstance(
            record, dict,
        ) else None
        if not isinstance(ordinal, int):
            ordinal = index
        synthetic_flag = bool(
            record.get("synthetic", False),
        ) if isinstance(record, dict) else False
        parsed.append(ReplayFrame(
            ordinal=int(ordinal), frame=frame, receipt_ns=receipt_ns,
            synthetic=synthetic_flag,
        ))
    parsed.sort(key=lambda item: (item.ordinal, item.receipt_ns or 0))
    return CaptureBundle(
        source_path=str(path),
        schema=str(bundle.get("schema", "")),
        endpoint=bundle.get("endpoint"),
        symbol=bundle.get("symbol"),
        evidence_class=(
            "SYNTHETIC_FIXTURE" if any(r.synthetic for r in parsed)
            else "CAPTURED"
        ),
        records=tuple(parsed),
    )


# ==================================================================
# Synthetic fixture generation (labelled; fault injection + soak only)
# ==================================================================


def synthetic_candle_frames(
    symbol: str,
    *,
    candles: int,
    seed: int = 7,
    start_price: float = 60000.0,
    start_ts_seconds: int = 1_700_000_400,
    resolution: str = "1m",
) -> tuple[ReplayFrame, ...]:
    """Deterministic synthetic candlestick frames (SYNTHETIC evidence).

    Shapes match the documented public candlestick schema exactly (``cst``
    / ``ts`` in microseconds) so the frames travel the same verified
    chain as captured data.  The OHLCV series for a given seed is exactly
    the repository's canonical deterministic pipeline feed
    (tests.test_pipeline_regressions ``make_candles``): alternating
    50-bar drift regimes with a periodic impulse candle, so structure
    scanners have real signal to find.  Candle starts are whole-minute
    aligned (the exchange convention the gap-repair validator enforces).
    Used for fault injection and soak runs only; never presented as
    captured exchange data.
    """
    noise_body_pct = 0.0015
    impulse_body_pct = 0.02
    if candles < 1:
        raise ValueError("synthetic_candle_frames requires candles >= 1")
    rng = random.Random(seed)
    # The exchange publish-time jitter uses its OWN stream so the OHLCV
    # series is byte-for-byte the canonical deterministic feed family
    # (tests.test_pipeline_regressions make_candles) for the same seed.
    jitter_rng = random.Random(seed + 1)
    window = 60
    records: list[ReplayFrame] = []
    price = float(start_price)
    for index in range(candles):
        start_seconds = start_ts_seconds + index * window
        cst_us = start_seconds * MICRO
        # deterministic feed family: alternating 50-bar drift regimes with
        # a periodic impulse candle, mirroring the repository's canonical
        # synthetic pipeline feed (tests.test_pipeline_regressions
        # make_candles) so structure scanners have real signal to find.
        drift = 0.15 if (index // 50) % 2 == 0 else -0.15
        if index % 50 == 25:
            body = price * impulse_body_pct * (1 if drift > 0 else -1)
        else:
            body = (
                price * noise_body_pct * rng.uniform(-1, 1)
                + price * 0.0004 * drift
            )
        open_p = price
        close_p = open_p + body
        high_p = max(open_p, close_p) + abs(body) * rng.uniform(0.05, 0.4)
        low_p = min(open_p, close_p) - abs(body) * rng.uniform(0.05, 0.4)
        if low_p <= 0:
            low_p = abs(body) + 1.0
        volume = rng.uniform(50, 500) * (3 if index % 50 == 25 else 1)
        frame = {
            "type": "candlestick_%s" % resolution,
            "o": round(open_p, 8),
            "h": round(high_p, 8),
            "l": round(low_p, 8),
            "c": round(close_p, 8),
            "v": round(volume, 6),
            "res": resolution,
            "sy": symbol,
            "cst": cst_us,
            "ts": cst_us + jitter_rng.randrange(1_000, 900_000),
        }
        records.append(ReplayFrame(
            ordinal=index + 1,
            frame=frame,
            receipt_ns=(start_seconds + 1) * 1_000_000_000,
            synthetic=True,
        ))
        price = close_p
    return tuple(records)


def make_synthetic_bundle(
    symbol: str,
    records: Iterable[ReplayFrame],
    *,
    endpoint: str = "synthetic://fault-injection",
    note: str = "",
) -> dict[str, Any]:
    """Bundle synthetic frames with explicit SYNTHETIC evidence labels."""
    return {
        "schema": CAPTURE_SCHEMA,
        "evidence_class": "SYNTHETIC_FIXTURE",
        "synthetic": True,
        "endpoint": endpoint,
        "symbol": symbol,
        "note": note,
        "frames": [
            {
                "receipt_ordinal": record.ordinal,
                "receipt_unix_ns": record.receipt_ns,
                "synthetic": True,
                "frame": record.frame,
            }
            for record in records
        ],
    }


