"""Phase 24 deterministic verified-transport replay harness.

Replays recorded (or clearly-labelled synthetic) public market frames
through the REAL production paper seam -- never a parallel pipeline:

    recorded frame record (receipt order)
      -> VerifiedPublicCandleTransport.ingest(frame, receipt_timestamp)
           -> DeltaPublicEventStream (normalization, finality, continuity)
           -> to_runtime_candle (fail-closed conversion)
           -> per-symbol SubscriptionWorker (6D: dedupe / order / health)
      -> RealTimeEngine._on_closed_candle (identity routing)
      -> PaperRuntime.process_closed_candle -> frozen InstitutionalPipeline
           (setup -> decision -> RiskEngine -> OrderIntent)
      -> BrokerEngine(dry_run=True) -> TradeSimulator -> TradeRegistry

Evidence classes are explicit and never mixed:

* ``CAPTURED``  -- frames parsed from a recorded
  ``quantengine.delta-public-capture.v1`` bundle (the same schema the
  repository's captured fixtures use).  Nothing is modified.
* ``SYNTHETIC_FIXTURE`` -- programmatically generated frames, determin-
  istically seeded, used for fault injection and soak runs only.  Every
  synthetic frame is labelled and counted separately from captured data.

The harness owns no network transport and no credentials.  It never
promotes a fixture result to live- or testnet-verified status, and it
never writes to an exchange.

Determinism: at ``speed=0`` (the default and the only speed the tests
use) the replay performs no wall-clock waiting at all; a controllable
``ReplayClock`` drives every scheduling decision (reconnect retries,
staleness, universe refresh cadence).  Faults are described by explicit
plan objects, so two runs with the same inputs produce identical
deterministic report sections (latency/runtime/memory are reported
separately as non-deterministic observations).
"""

